auto RenderContext::indent() const -> RenderContext {
    auto result{*this};
    ++result.indent_level;
    return result;
}

auto RenderContext::apply_indent(std::string_view text) const -> std::string {
    auto const prefix{std::string(static_cast<std::size_t>(indent_level), ' ') +
                      std::string(static_cast<std::size_t>(indent_level) *
                                      (indent_text.size() > 1 ? indent_text.size() - 1 : 0),
                                  ' ')};
    std::ostringstream output;
    std::istringstream input{std::string{text}};
    std::string line;
    bool first{true};
    while (std::getline(input, line)) {
        if (!first) {
            output << '\n';
        }
        if (!line.empty()) {
            output << prefix << line;
        }
        first = false;
    }
    if (!text.empty() && text.back() == '\n') {
        output << '\n';
    }
    return output.str();
}

auto include_is_system(Include const& include) -> bool {
    if (include.system.has_value()) {
        return *include.system;
    }
    auto const slash{include.path.find_last_of('/')};
    auto const filename{include.path.substr(slash == std::string::npos ? 0 : slash + 1)};
    return filename.find('.') == std::string::npos;
}

auto children(Node const& node) -> Nodes const* {
    return std::visit(
        [](auto const& value) -> Nodes const* {
            using T = std::decay_t<decltype(value)>;
            if constexpr (std::is_same_v<T, Struct> || std::is_same_v<T, Namespace>) {
                return &value.children;
            } else if constexpr (std::is_same_v<T, Function>) {
                return value.declaration ? nullptr : &value.spec.body;
            } else {
                return nullptr;
            }
        },
        node);
}

auto dependencies(Node const& node) -> std::vector<TypeDependency> {
    return std::visit(
        [](auto const& value) -> std::vector<TypeDependency> {
            using T = std::decay_t<decltype(value)>;
            if constexpr (std::is_same_v<T, Raw> || std::is_same_v<T, ExpressionStatement> ||
                          std::is_same_v<T, ReturnStatement> ||
                          std::is_same_v<T, AssignmentStatement>) {
                return value.dependencies;
            } else if constexpr (std::is_same_v<T, UsingDeclaration> || std::is_same_v<T, Member> ||
                                 std::is_same_v<T, VariableDeclarationStatement>) {
                return value.type.dependencies;
            } else if constexpr (std::is_same_v<T, Function>) {
                auto result{value.spec.return_type.dependencies};
                if (value.spec.qualifiers.trailing_return_type.has_value()) {
                    result.insert(result.end(),
                                  value.spec.qualifiers.trailing_return_type->dependencies.begin(),
                                  value.spec.qualifiers.trailing_return_type->dependencies.end());
                }
                for (auto const& parameter : value.spec.parameters) {
                    result.insert(result.end(),
                                  parameter.type.dependencies.begin(),
                                  parameter.type.dependencies.end());
                }
                return result;
            } else if constexpr (std::is_same_v<T, Struct>) {
                auto result{value.dependencies};
                for (auto const& base : value.bases) {
                    result.insert(result.end(), base.dependencies.begin(), base.dependencies.end());
                }
                return result;
            } else {
                return {};
            }
        },
        node);
}

auto render_nodes(Nodes const& nodes, RenderContext const& context, int default_newlines)
    -> std::string {
    std::string output;
    for (auto const& node : nodes) {
        if (auto const* newlines{node.get_if<NewLines>()}; newlines != nullptr) {
            output = trim_newlines(std::move(output));
            output.append(static_cast<std::size_t>(newlines->count), '\n');
            continue;
        }
        auto rendered{render(node, context)};
        if (rendered.empty()) {
            continue;
        }
        if (!output.empty() && output.back() != '\n') {
            output.append(static_cast<std::size_t>(default_newlines), '\n');
        }
        output += rendered;
    }
    return output;
}

auto render(Node const& node, RenderContext const& context) -> std::string {
    return std::visit(
        [&](auto const& value) -> std::string {
            using T = std::decay_t<decltype(value)>;
            if constexpr (std::is_same_v<T, Raw>) {
                return context.apply_indent(value.text);
            } else if constexpr (std::is_same_v<T, ExpressionStatement>) {
                return context.apply_indent(value.expression + ";");
            } else if constexpr (std::is_same_v<T, ReturnStatement>) {
                return context.apply_indent(
                    value.expression.has_value() ? "return " + *value.expression + ";" : "return;");
            } else if constexpr (std::is_same_v<T, AssignmentStatement>) {
                return context.apply_indent(value.target + " = " + value.value + ";");
            } else if constexpr (std::is_same_v<T, VariableDeclarationStatement>) {
                return context.apply_indent(value.type.spelling + " " + value.name + "{" +
                                            value.initializer + "};");
            } else if constexpr (std::is_same_v<T, NewLines>) {
                return std::string(static_cast<std::size_t>(value.count), '\n');
            } else if constexpr (std::is_same_v<T, AccessSpecifier>) {
                auto width{static_cast<std::size_t>(context.indent_level) *
                           context.indent_text.size()};
                if (value.indentation == AccessSpecifier::Indentation::outdented && width >= 2) {
                    width -= 2;
                }
                return std::string(width, ' ') + value.access + ":";
            } else if constexpr (std::is_same_v<T, Include>) {
                auto const left{include_is_system(value) ? '<' : '"'};
                auto const right{include_is_system(value) ? '>' : '"'};
                return context.apply_indent("#include " + std::string(1, left) + value.path +
                                            right);
            } else if constexpr (std::is_same_v<T, IncludeDependencies>) {
                std::vector<std::string> groups;
                for (auto const& group : context.include_groups) {
                    std::vector<std::string> includes;
                    for (auto const& include : group) {
                        includes.push_back(render(Node{include}, context));
                    }
                    groups.push_back(join(includes, "\n"));
                }
                return join(groups, "\n\n");
            } else if constexpr (std::is_same_v<T, ForwardDeclaration>) {
                return context.apply_indent(value.kind + " " + value.name + ";");
            } else if constexpr (std::is_same_v<T, FriendDeclaration>) {
                return context.apply_indent("friend " + value.kind + " " + value.name + ";");
            } else if constexpr (std::is_same_v<T, UsingDeclaration>) {
                return context.apply_indent("using " + value.name + " = " + value.type.spelling +
                                            ";");
            } else if constexpr (std::is_same_v<T, Member>) {
                auto initializer{value.initializer.has_value() ? "{" + *value.initializer + "}"
                                                               : ""};
                return context.apply_indent(value.type.spelling + " " + value.name + initializer +
                                            ";");
            } else if constexpr (std::is_same_v<T, Function>) {
                auto const signature{context.apply_indent(render_signature(value))};
                if (value.declaration ||
                    value.spec.qualifiers.disposition != FunctionDisposition::normal) {
                    return signature + ";";
                }
                if (value.spec.formatting.body_layout == FunctionFormatting::BodyLayout::compact) {
                    auto body_context{context};
                    body_context.indent_level = 0;
                    auto const body{render_nodes(value.spec.body, body_context, 1)};
                    return signature + " { " + body + " }";
                }
                auto const body{render_nodes(value.spec.body, context.indent(), 1)};
                auto const opening{value.spec.formatting.opening_brace_placement ==
                                           FunctionFormatting::OpeningBracePlacement::separate_line
                                       ? "\n" + context.apply_indent("{")
                                       : " {"};
                return signature + opening + "\n" + body + "\n" + context.apply_indent("}");
            } else if constexpr (std::is_same_v<T, Struct>) {
                std::vector<std::string> bases;
                for (auto const& base : value.bases) {
                    bases.push_back(base.spelling);
                }
                auto header{value.record_kind};
                if (value.export_specifier.has_value()) {
                    header += " " + *value.export_specifier;
                }
                header += " " + value.name;
                if (!bases.empty()) {
                    header += " : " + join(bases, ", ");
                }
                if (value.template_parameters.has_value()) {
                    auto template_header{"template <" + *value.template_parameters + ">\n"};
                    if (value.requires_clause.has_value()) {
                        template_header += "    requires " + *value.requires_clause + "\n";
                    }
                    header = template_header + header;
                }
                return context.apply_indent(header + " {") + "\n" +
                       render_nodes(value.children, context.indent(), 2) + "\n" +
                       context.apply_indent("};");
            } else if constexpr (std::is_same_v<T, Namespace>) {
                return context.apply_indent("namespace " + value.name + " {") + "\n" +
                       render_nodes(value.children, context, 2) + "\n" +
                       context.apply_indent("} // namespace " + value.name);
            }
        },
        node);
}

auto render(CppFile const& file) -> std::string {
    RenderContext context;
    context.include_groups = include_groups(file);

    std::vector<std::string> sections{generated_file_warning};
    sections.insert(sections.end(), file.prologue.begin(), file.prologue.end());
    if (file.pragma_once) {
        sections.emplace_back("#pragma once");
    }
    if (!file.nodes.empty()) {
        sections.push_back(render_nodes(file.nodes, context, 1));
    }
    sections.insert(sections.end(), file.epilogue.begin(), file.epilogue.end());
    auto rendered{trim_newlines(join(sections, "\n\n"))};
    if (file.clang_format_off) {
        return "// clang-format off\n" + rendered + "\n// clang-format on\n";
    }
    return rendered + "\n";
}

auto raw(std::string text) -> Node {
    return Raw{std::move(text), {}};
}

auto raw(std::string text, std::vector<TypeDependency> type_dependencies) -> Node {
    return Raw{std::move(text), std::move(type_dependencies)};
}

auto lines(int count) -> Node {
    if (count <= 0) {
        throw std::invalid_argument{"NewLines count must be positive"};
    }
    return NewLines{count};
}

auto NodeListBuilder::add(Node node) -> NodeListBuilder& {
    nodes_.push_back(std::move(node));
    return *this;
}

auto NodeListBuilder::add(Node node, int trailing_new_lines) -> NodeListBuilder& {
    return add(std::move(node)).new_lines(trailing_new_lines);
}

auto NodeListBuilder::append(Nodes nodes) -> NodeListBuilder& {
    for (auto& node : nodes) {
        nodes_.push_back(std::move(node));
    }
    return *this;
}

auto NodeListBuilder::new_lines(int count) -> NodeListBuilder& {
    nodes_.push_back(lines(count));
    return *this;
}

auto NodeListBuilder::build() -> Nodes {
    return std::move(nodes_);
}

auto declaration(FunctionSpec spec) -> Node {
    return Function{std::move(spec), std::nullopt, true, false};
}

auto header_function(FunctionSpec spec) -> Node {
    if (!spec.is_inline) {
        return declaration(std::move(spec));
    }
    return Function{std::move(spec), std::nullopt, false, true};
}

auto definition(FunctionSpec spec, std::string owner) -> Node {
    return Function{std::move(spec), std::move(owner), false, false};
}

