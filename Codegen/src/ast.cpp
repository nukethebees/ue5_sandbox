constexpr auto generated_file_warning = "// This file is autogenerated. Do not edit by hand.\n"
                                        "// Edit Codegen/manifests and regenerate it instead.";

auto join(std::vector<std::string> const& values, std::string_view separator) -> std::string {
    std::ostringstream output;
    auto const count{values.size()};
    for (std::size_t index{0}; index < count; ++index) {
        if (index != 0) {
            output << separator;
        }
        output << values[index];
    }
    return output.str();
}

auto trim_newlines(std::string value) -> std::string {
    while (!value.empty() && value.back() == '\n') {
        value.pop_back();
    }
    return value;
}

auto has_auto_type_specifier(std::string const& spelling) -> bool {
    std::istringstream input{spelling};
    std::string specifier;
    while (input >> specifier) {
        if (specifier == "auto") {
            return true;
        }
    }
    return false;
}

auto render_parameter(FunctionParameter const& parameter, bool include_default) -> std::string {
    auto result{parameter.type.spelling};
    if (!parameter.name.empty()) {
        result += " " + parameter.name;
    }
    if (include_default && parameter.default_value.has_value()) {
        result += " = " + *parameter.default_value;
    }
    return result;
}

void validate_function(Function const& function) {
    auto const& spec{function.spec};
    auto const& qualifiers{spec.qualifiers};
    auto const context{"Function '" + spec.name + "'"};

    if (qualifiers.is_noexcept && qualifiers.noexcept_condition.has_value()) {
        throw std::invalid_argument{context +
                                    " cannot combine unconditional and conditional noexcept"};
    }
    if (qualifiers.trailing_return_type.has_value() &&
        !has_auto_type_specifier(spec.return_type.spelling)) {
        throw std::invalid_argument{context +
                                    " trailing return type requires an 'auto' type specifier"};
    }
    if (spec.is_static && qualifiers.is_const) {
        throw std::invalid_argument{context + " static function cannot be const"};
    }
    if (qualifiers.disposition != FunctionDisposition::normal) {
        if (!spec.body.empty()) {
            throw std::invalid_argument{context +
                                        " defaulted or deleted function cannot have a body"};
        }
        if (qualifiers.disposition == FunctionDisposition::deleted && function.owner.has_value()) {
            throw std::invalid_argument{context +
                                        " deleted function cannot be an out-of-line definition"};
        }
    }
}

auto render_signature(Function const& function) -> std::string {
    validate_function(function);
    auto const& spec{function.spec};
    std::vector<std::string> parameters;
    parameters.reserve(spec.parameters.size());
    for (auto const& parameter : spec.parameters) {
        parameters.push_back(
            render_parameter(parameter, function.declaration || function.is_header));
    }

    auto const static_prefix{spec.is_static && !function.owner.has_value() ? "static " : ""};
    auto const qualified_name{function.owner.has_value() ? *function.owner + "::" + spec.name
                                                         : spec.name};
    auto signature{std::string{static_prefix}};
    if (!spec.return_type.spelling.empty()) {
        signature += spec.return_type.spelling + " ";
    }
    signature += qualified_name + "(" + join(parameters, ", ") + ")";
    if (spec.qualifiers.is_const) {
        signature += " const";
    }
    if (spec.qualifiers.noexcept_condition.has_value()) {
        signature += " noexcept(" + *spec.qualifiers.noexcept_condition + ")";
    } else if (spec.qualifiers.is_noexcept) {
        signature += " noexcept";
    }
    if (spec.qualifiers.trailing_return_type.has_value()) {
        signature += spec.formatting.trailing_return_placement ==
                             FunctionFormatting::TrailingReturnPlacement::next_line
                       ? "\n    -> "
                       : " -> ";
        signature += spec.qualifiers.trailing_return_type->spelling;
    }
    if (spec.requires_clause.has_value()) {
        switch (spec.formatting.requires_placement) {
            case FunctionFormatting::RequiresPlacement::trailing_next_line:
                signature += "\n    requires " + *spec.requires_clause;
                break;
            case FunctionFormatting::RequiresPlacement::trailing_same_line:
                signature += " requires " + *spec.requires_clause;
                break;
            case FunctionFormatting::RequiresPlacement::before_signature:
                signature = "    requires " + *spec.requires_clause + "\n" + signature;
                break;
        }
    }
    if (spec.template_parameters.has_value()) {
        signature =
            "template <" + *spec.template_parameters + ">" +
            (spec.formatting.template_placement == FunctionFormatting::TemplatePlacement::same_line
                 ? " "
                 : "\n") +
            signature;
    }
    switch (spec.qualifiers.disposition) {
        case FunctionDisposition::normal:
            break;
        case FunctionDisposition::defaulted:
            signature += spec.formatting.disposition_placement ==
                                 FunctionFormatting::DispositionPlacement::next_line
                           ? "\n= default"
                           : " = default";
            break;
        case FunctionDisposition::deleted:
            signature += spec.formatting.disposition_placement ==
                                 FunctionFormatting::DispositionPlacement::next_line
                           ? "\n= delete"
                           : " = delete";
            break;
    }
    return signature;
}

void collect_dependencies(Node const& node, std::vector<TypeDependency>& result) {
    auto direct{dependencies(node)};
    result.insert(result.end(), direct.begin(), direct.end());
    if (auto const* nested{children(node)}; nested != nullptr) {
        for (auto const& child : *nested) {
            collect_dependencies(child, result);
        }
    }
}

void collect_dependency_includes(TypeDependency const& dependency, std::set<std::string>& paths) {
    if (dependency.header.has_value()) {
        paths.insert(*dependency.header);
    }
    for (auto const& nested : dependency.dependencies) {
        collect_dependency_includes(nested, paths);
    }
}

auto include_groups(CppFile const& file) -> std::vector<std::vector<Include>> {
    std::vector<TypeDependency> all_dependencies;
    for (auto const& node : file.nodes) {
        collect_dependencies(node, all_dependencies);
    }

    std::set<std::string> paths;
    for (auto const& dependency : all_dependencies) {
        collect_dependency_includes(dependency, paths);
    }

    std::vector<std::vector<Include>> result;
    for (auto const& prefix : file.include_order) {
        std::vector<Include> group;
        for (auto iterator{paths.begin()}; iterator != paths.end();) {
            if (iterator->starts_with(prefix)) {
                group.push_back(Include{*iterator, std::nullopt});
                iterator = paths.erase(iterator);
            } else {
                ++iterator;
            }
        }
        if (!group.empty()) {
            result.push_back(std::move(group));
        }
    }

    std::vector<Include> quoted;
    std::vector<Include> system;
    for (auto const& path : paths) {
        Include include{path, std::nullopt};
        (include_is_system(include) ? system : quoted).push_back(std::move(include));
    }
    if (!quoted.empty()) {
        result.push_back(std::move(quoted));
    }
    if (!system.empty()) {
        result.push_back(std::move(system));
    }
    return result;
}

