auto lower_modules(Manifest const& manifest) -> std::vector<Module> {
    detail::validate_manifest(manifest);
    std::vector<Module> result;
    for (auto const& schema : manifest.modules) {
        std::visit(
            [&](auto const& module) {
                using T = std::decay_t<decltype(module)>;
                if constexpr (std::is_same_v<T, EnumModuleSchema>) {
                    result.push_back(detail::lower_enum_module(module, manifest.types));
                } else if constexpr (std::is_same_v<T, SoaModuleSchema>) {
                    result.push_back(detail::lower_soa_module(module, manifest.types));
                } else if constexpr (std::is_same_v<T, StaticTableModuleSchema>) {
                    result.push_back(detail::lower_static_table_module(module, manifest.types));
                } else if constexpr (std::is_same_v<T, FacadeModuleSchema>) {
                    result.push_back(detail::lower_facade_module(module, manifest.types));
                } else if constexpr (std::is_same_v<T, HomogeneousModuleSchema>) {
                    result.push_back(detail::lower_homogeneous_module(module, manifest.types));
                } else if constexpr (std::is_same_v<T, VectorModuleSchema>) {
                    result.push_back(detail::lower_vector_module(module, manifest.types));
                } else if constexpr (std::is_same_v<T, UmbrellaModuleSchema>) {
                    result.push_back(lower_umbrella(module));
                }
            },
            schema);
    }
    return result;
}

auto render_modules(std::vector<Module> const& modules) -> std::vector<GeneratedFile> {
    std::vector<GeneratedFile> result;
    std::set<std::string> paths;
    for (auto const& module : modules) {
        for (auto const* file : {module.header ? &*module.header : nullptr,
                                 module.source ? &*module.source : nullptr}) {
            if (file == nullptr) {
                continue;
            }
            auto const normalized{file->path.lexically_normal()};
            if (!paths.insert(detail::output_path_key(normalized)).second) {
                throw std::invalid_argument{"Duplicate generated output path: " +
                                            normalized.string()};
            }
            result.push_back(GeneratedFile{normalized, render(*file)});
        }
    }
    return result;
}

auto generate_files(std::vector<GeneratedFile> const& files,
                    std::filesystem::path const& project_root,
                    std::filesystem::path const& output_root,
                    bool check_only) -> int {
    std::map<std::string, GeneratedFile const*> expected;
    for (auto const& file : files) {
        auto const relative{safe_relative_output_path(file.path, project_root)};
        auto const path{relative.generic_string()};
        if (path == output_inventory_name) {
            throw std::invalid_argument{"Generated output path is reserved: " + path};
        }
        if (!expected.emplace(detail::output_path_key(relative), &file).second) {
            throw std::invalid_argument{"Duplicate generated output path: " + path};
        }
    }

    std::set<std::string> expected_paths;
    for (auto const& [unused, file] : expected) {
        static_cast<void>(unused);
        expected_paths.insert(safe_relative_output_path(file->path, project_root).generic_string());
    }
    auto const inventory_path{output_root / output_inventory_name};
    auto const previous_paths{read_inventory(inventory_path)};
    bool stale{false};
    if (!previous_paths.has_value()) {
        if (check_only) {
            stale = true;
            std::cout << "Missing generated output inventory\n";
        }
    } else {
        for (auto const& previous : *previous_paths) {
            if (expected_paths.contains(previous)) {
                continue;
            }
            auto const destination{output_root / std::filesystem::path{previous}};
            validate_destination(destination, output_root);
            if (check_only) {
                stale = true;
                std::cout << "Orphaned " << previous << '\n';
                continue;
            }
            if (std::filesystem::exists(destination) && !is_generated_file(destination)) {
                throw std::runtime_error{"Refusing to remove non-generated orphan: " +
                                         destination.string()};
            }
            std::error_code error;
            std::filesystem::remove(destination, error);
            if (error) {
                throw std::filesystem::filesystem_error{
                    "Cannot remove orphaned generated file", destination, error};
            }
            std::cout << "Removed " << previous << '\n';
        }
    }
    for (auto const& file : files) {
        auto const relative{safe_relative_output_path(file.path, project_root)};
        auto const destination{output_root / relative};
        validate_destination(destination, output_root);
        auto const current{read_file(destination)};
        if (current.has_value() &&
            normalize_line_endings(*current) == normalize_line_endings(file.content)) {
            std::cout << "Unchanged " << relative.generic_string() << '\n';
            continue;
        }
        if (check_only) {
            stale = true;
            std::cout << "Stale " << relative.generic_string() << '\n';
            continue;
        }
        write_file_atomically(destination, file.content, output_root);
        std::cout << "Wrote " << relative.generic_string() << '\n';
    }
    if (previous_paths != std::optional<std::set<std::string>>{expected_paths}) {
        if (check_only) {
            stale = true;
            std::cout << "Stale generated output inventory\n";
        } else {
            write_file_atomically(inventory_path, inventory_content(expected_paths), output_root);
            std::cout << "Wrote " << output_inventory_name << '\n';
        }
    }
    if (stale) {
        std::cout << "Generated files are stale. Run the generate-code CMake workflow.\n";
        return 1;
    }
    return 0;
}

