#include "renderer.h"

#include <string_view>
#include <type_traits>
#include <utility>

namespace slate_codegen::detail {
namespace {

class Renderer {
  public:
    explicit Renderer(std::string source_path) : source_path_{std::move(source_path)} {}

    auto render(Child const& root) -> std::string {
        append_line(0, "// This file is autogenerated. Do not edit by hand.");
        append_line(0, "// Source: " + source_path_);
        append_line(0, {});
        append_line(0, "return");
        append_source_line(root.span);
        render_child(root, 4);
        output_.pop_back();
        output_ += ";\n";
        return output_;
    }

  private:
    void append_line(std::size_t const indent, std::string_view const text) {
        output_.append(indent, ' ');
        output_.append(text);
        output_ += '\n';
    }

    void append_source_line(SourceSpan const span) {
        append_line(0,
                    "#line " + std::to_string(span.line) + " \"" +
                        escape_cpp_string(source_path_) + "\"");
    }

    void render_child(Child const& child, std::size_t const indent) {
        std::visit(
            [&](auto const& value) {
                using T = std::decay_t<decltype(value)>;
                if constexpr (std::is_same_v<T, Widget>) {
                    render_widget(value, indent);
                } else {
                    render_vbox(value, indent);
                }
            },
            child.value);
    }

    void render_widget(Widget const& widget, std::size_t const indent) {
        append_line(indent, "SNew(" + widget.type + ")");
        for (auto const& argument : widget.arguments) {
            auto const value{render_value(argument.value)};
            auto const invocation{"." + argument.name + "(" + value + ")"};
            if (indent + 4 + invocation.size() <= 100) {
                append_line(indent + 4, invocation);
            } else {
                append_line(indent + 4, "." + argument.name + "(");
                append_line(indent + 8, value + ")");
            }
        }
        if (widget.content) {
            append_line(indent + 4, "[");
            render_child(*widget.content, indent + 8);
            append_line(indent + 4, "]");
        }
        for (auto const& slot : widget.named_slots) {
            append_line(indent + 4, "." + slot.name + "()");
            append_line(indent + 4, "[");
            render_child(*slot.child, indent + 8);
            append_line(indent + 4, "]");
        }
    }

    void render_vbox(VBox const& box, std::size_t const indent) {
        append_line(indent, "SNew(SVerticalBox)");
        for (auto const& slot : box.slots) {
            append_line(indent + 4, "+ " + render_slot_helper(slot));
            if (slot.horizontal_alignment) {
                append_line(indent + 8,
                            ".HAlign(" + horizontal_alignment(*slot.horizontal_alignment) + ")");
            }
            if (slot.vertical_alignment) {
                append_line(indent + 8,
                            ".VAlign(" + vertical_alignment(*slot.vertical_alignment) + ")");
            }
            append_line(indent + 8, "[");
            render_child(*slot.child, indent + 12);
            append_line(indent + 8, "]");
        }
    }

    static auto render_value(Value const& value) -> std::string {
        if (value.kind == ValueKind::text) {
            return "FText::FromString(TEXT(\"" + escape_cpp_string(value.text) + "\"))";
        }
        return value.text;
    }

    static auto render_slot_helper(BoxSlot const& slot) -> std::string {
        auto const padding{render_padding(slot.padding)};
        if (!slot.fill) {
            return padding.empty() ? "SandboxUI::Slate::vbox_auto_slot()"
                                   : "SandboxUI::Slate::vbox_auto_slot(" + padding + ")";
        }
        if (slot.weight) {
            auto const weight{float_literal(*slot.weight)};
            return padding.empty() ? "SandboxUI::Slate::vbox_fill_slot(" + weight + ")"
                                   : "SandboxUI::Slate::vbox_fill_slot(" + weight + ", " +
                                         padding + ")";
        }
        return padding.empty() ? "SandboxUI::Slate::vbox_fill_slot()"
                               : "SandboxUI::Slate::vbox_fill_slot(1.0f, " + padding + ")";
    }

    static auto render_padding(std::vector<std::string> const& values) -> std::string {
        if (values.empty()) {
            return {};
        }
        std::string result{"FMargin{"};
        for (std::size_t index{}; index < values.size(); ++index) {
            if (index != 0) {
                result += ", ";
            }
            result += float_literal(values[index]);
        }
        result += '}';
        return result;
    }

    static auto float_literal(std::string value) -> std::string {
        if (value.find('.') == std::string::npos) {
            value += ".0";
        }
        value += 'f';
        return value;
    }

    static auto horizontal_alignment(std::string_view const value) -> std::string {
        if (value == "left") {
            return "HAlign_Left";
        }
        if (value == "center") {
            return "HAlign_Center";
        }
        if (value == "right") {
            return "HAlign_Right";
        }
        return "HAlign_Fill";
    }

    static auto vertical_alignment(std::string_view const value) -> std::string {
        if (value == "top") {
            return "VAlign_Top";
        }
        if (value == "center") {
            return "VAlign_Center";
        }
        if (value == "bottom") {
            return "VAlign_Bottom";
        }
        return "VAlign_Fill";
    }

    static auto escape_cpp_string(std::string_view const value) -> std::string {
        std::string result;
        for (auto const character : value) {
            switch (character) {
            case '\\':
                result += "\\\\";
                break;
            case '"':
                result += "\\\"";
                break;
            case '\n':
                result += "\\n";
                break;
            case '\r':
                result += "\\r";
                break;
            case '\t':
                result += "\\t";
                break;
            default:
                result += character;
                break;
            }
        }
        return result;
    }

    std::string source_path_;
    std::string output_;
};

}

auto render(std::string source_path, Child const& root) -> std::string {
    return Renderer{std::move(source_path)}.render(root);
}

}
