constexpr auto output_inventory_name = ".lispb-outputs";
constexpr auto output_inventory_header = "lispb-outputs-v1";
constexpr auto generated_file_warning = "// This file is autogenerated. Do not edit by hand.";

auto safe_relative_output_path(std::filesystem::path const& path,
                               std::filesystem::path const& project_root) -> std::filesystem::path {
    auto relative{path.is_absolute() ? path.lexically_relative(project_root) : path};
    relative = relative.lexically_normal();
    if (relative.empty() || relative == "." || relative.is_absolute() || relative.has_root_path()) {
        throw std::invalid_argument{"Generated output path is outside the output root: " +
                                    path.string()};
    }
    for (auto const& component : relative) {
        if (component == "..") {
            throw std::invalid_argument{"Generated output path is outside the output root: " +
                                        path.string()};
        }
    }
    return relative;
}

auto path_is_within(std::filesystem::path const& path, std::filesystem::path const& root) -> bool {
    auto const relative{path.lexically_relative(root)};
    if (relative.empty() || relative.is_absolute() || relative.has_root_path()) {
        return false;
    }
    return std::ranges::none_of(relative, [](auto const& component) { return component == ".."; });
}

void validate_destination(std::filesystem::path const& destination,
                          std::filesystem::path const& output_root) {
    std::error_code error;
    auto const canonical_root{std::filesystem::weakly_canonical(output_root, error)};
    if (error) {
        throw std::filesystem::filesystem_error{
            "Cannot resolve generated output root", output_root, error};
    }
    auto const canonical_parent{
        std::filesystem::weakly_canonical(destination.parent_path(), error)};
    if (error) {
        throw std::filesystem::filesystem_error{
            "Cannot resolve generated output directory", destination.parent_path(), error};
    }
    if (!path_is_within(canonical_parent, canonical_root) && canonical_parent != canonical_root) {
        throw std::invalid_argument{"Generated output path escapes the output root: " +
                                    destination.string()};
    }
    auto const destination_exists{std::filesystem::exists(destination, error)};
    if (error) {
        throw std::filesystem::filesystem_error{
            "Cannot inspect generated output path", destination, error};
    }
    if (destination_exists && std::filesystem::is_symlink(destination, error)) {
        throw std::invalid_argument{"Generated output file must not be a symbolic link: " +
                                    destination.string()};
    }
    if (error) {
        throw std::filesystem::filesystem_error{
            "Cannot inspect generated output path", destination, error};
    }
}

auto read_file(std::filesystem::path const& path) -> std::optional<std::string> {
    std::ifstream input{path, std::ios::binary};
    if (!input) {
        return std::nullopt;
    }
    return std::string{std::istreambuf_iterator<char>{input}, std::istreambuf_iterator<char>{}};
}

void replace_file(std::filesystem::path const& source, std::filesystem::path const& destination) {
#if defined(_WIN32)
    if (!MoveFileExW(source.c_str(),
                     destination.c_str(),
                     MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH)) {
        throw std::filesystem::filesystem_error{
            "Cannot replace generated file",
            source,
            destination,
            std::error_code{static_cast<int>(GetLastError()), std::system_category()}};
    }
#else
    std::filesystem::rename(source, destination);
#endif
}

void write_file_atomically(std::filesystem::path const& destination,
                           std::string_view const content,
                           std::filesystem::path const& output_root) {
    std::filesystem::create_directories(destination.parent_path());
    validate_destination(destination, output_root);

    auto temporary{destination};
    temporary += ".lispb.tmp";
    std::error_code ignored;
    std::filesystem::remove(temporary, ignored);
    try {
        std::ofstream output{temporary, std::ios::binary | std::ios::trunc};
        if (!output) {
            throw std::runtime_error{"Cannot write generated file: " + temporary.string()};
        }
        output.write(content.data(), static_cast<std::streamsize>(content.size()));
        output.close();
        if (!output) {
            throw std::runtime_error{"Failed while writing generated file: " + temporary.string()};
        }
        replace_file(temporary, destination);
    } catch (...) {
        std::filesystem::remove(temporary, ignored);
        throw;
    }
}

auto inventory_content(std::set<std::string> const& paths) -> std::string {
    std::string result{output_inventory_header};
    result += '\n';
    for (auto const& path : paths) {
        result += path + '\n';
    }
    return result;
}

auto read_inventory(std::filesystem::path const& path) -> std::optional<std::set<std::string>> {
    auto const content{read_file(path)};
    if (!content.has_value()) {
        return std::nullopt;
    }
    std::istringstream input{*content};
    std::string line;
    std::getline(input, line);
    if (!line.empty() && line.back() == '\r') {
        line.pop_back();
    }
    if (line != output_inventory_header) {
        throw std::runtime_error{"Invalid generated output inventory: " + path.string()};
    }
    std::set<std::string> result;
    while (std::getline(input, line)) {
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
        }
        if (line.empty()) {
            continue;
        }
        auto const relative{safe_relative_output_path(line, {})};
        if (relative.generic_string() != line || !result.insert(line).second) {
            throw std::runtime_error{"Invalid path in generated output inventory: " + line};
        }
    }
    return result;
}

auto is_generated_file(std::filesystem::path const& path) -> bool {
    auto const content{read_file(path)};
    return content.has_value() && content->contains(generated_file_warning);
}

