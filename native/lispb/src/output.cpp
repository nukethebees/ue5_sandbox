static auto publish_text_artifacts(Compilation& compilation,
                                   std::filesystem::path const& project_root,
                                   std::filesystem::path const& output_root,
                                   bool check_only) -> int {
    std::map<std::string, ArtifactId> expected;
    for (auto const id : compilation.artifacts) {
        if (id.kind() != ArtifactKind::text) {
            throw std::invalid_argument{"Tracked Lispb outputs must be text files"};
        }
        auto const relative{safe_relative_output_path(compilation.path(id), project_root)};
        auto const path{relative.generic_string()};
        if (path == output_inventory_name) {
            throw std::invalid_argument{"Generated output path is reserved: " + path};
        }
        if (!expected.emplace(lispb::codegen::output_path_key(relative), id).second) {
            throw std::invalid_argument{"Duplicate generated output path: " + path};
        }
    }

    // Format before comparing or changing any destinations, including in --check mode.
    for (auto const id : compilation.artifacts) {
        if (compilation.needs_formatting(id)) {
            compilation.set_formatted_text(
                id,
                lispb::codegen::detail::format_generated(
                    compilation.text(id),
                    project_root / safe_relative_output_path(compilation.path(id), project_root)));
        }
    }

    std::set<std::string> expected_paths;
    for (auto const& [unused, id] : expected) {
        static_cast<void>(unused);
        expected_paths.insert(
            safe_relative_output_path(compilation.path(id), project_root).generic_string());
    }
    auto const inventory_path{output_root / output_inventory_name};
    auto const previous_paths{read_inventory(inventory_path)};
    bool stale{false};
    if (!previous_paths.has_value()) {
        if (check_only) {
            stale = true;
            std::cout << "Missing generated output inventory\n";
        }
    } else {
        for (auto const& previous : *previous_paths) {
            if (expected_paths.contains(previous)) {
                continue;
            }
            auto const destination{output_root / std::filesystem::path{previous}};
            validate_destination(destination, output_root);
            if (check_only) {
                stale = true;
                std::cout << "Orphaned " << previous << '\n';
                continue;
            }
            if (std::filesystem::exists(destination) && !is_generated_file(destination)) {
                throw std::runtime_error{"Refusing to remove non-generated orphan: " +
                                         destination.string()};
            }
            std::error_code error;
            std::filesystem::remove(destination, error);
            if (error) {
                throw std::filesystem::filesystem_error{
                    "Cannot remove orphaned generated file", destination, error};
            }
            std::cout << "Removed " << previous << '\n';
        }
    }
    for (auto const id : compilation.artifacts) {
        auto const relative{safe_relative_output_path(compilation.path(id), project_root)};
        auto const destination{output_root / relative};
        validate_destination(destination, output_root);
        auto const current{read_file(destination)};
        if (current.has_value() && *current == compilation.text(id)) {
            std::cout << "Unchanged " << relative.generic_string() << '\n';
            continue;
        }
        if (check_only) {
            stale = true;
            std::cout << "Stale " << relative.generic_string() << '\n';
            continue;
        }
        write_file_atomically(destination, compilation.text(id), output_root);
        std::cout << "Wrote " << relative.generic_string() << '\n';
    }
    if (previous_paths != std::optional<std::set<std::string>>{expected_paths}) {
        if (check_only) {
            stale = true;
            std::cout << "Stale generated output inventory\n";
        } else {
            write_file_atomically(inventory_path, inventory_content(expected_paths), output_root);
            std::cout << "Wrote " << output_inventory_name << '\n';
        }
    }
    if (stale) {
        std::cout << "Generated files are stale.\n";
        return 1;
    }
    return 0;
}

auto publish(Compilation& compilation, PublicationOptions const& options) -> int {
    if (options.track_outputs) {
        return publish_text_artifacts(
            compilation, options.path_base, options.output_root, options.check_only);
    }

    bool stale{false};
    std::set<std::string> paths;
    for (auto const artifact : compilation.artifacts) {
        auto const& path{compilation.path(artifact)};
        auto const relative{safe_relative_output_path(path, options.path_base)};
        if (!paths.insert(lispb::codegen::output_path_key(relative)).second) {
            throw std::invalid_argument{"Duplicate generated output path: " +
                                        relative.generic_string()};
        }

        auto const destination{options.output_root / relative};
        validate_destination(destination, options.output_root);
        auto const current{read_file(destination)};
        std::string_view content;
        if (artifact.kind() == ArtifactKind::text) {
            if (compilation.needs_formatting(artifact)) {
                compilation.set_formatted_text(artifact,
                                               lispb::codegen::detail::format_generated(
                                                   compilation.text(artifact), destination));
            }
            content = compilation.text(artifact);
        } else {
            auto const bytes{compilation.binary(artifact)};
            if (!bytes.empty()) {
                content = {reinterpret_cast<char const*>(bytes.data()), bytes.size()};
            }
        }
        auto const equal{current && *current == content};
        if (equal) {
            std::cout << "Unchanged " << relative.generic_string() << '\n';
            continue;
        }
        if (options.check_only) {
            stale = true;
            std::cout << "Stale " << relative.generic_string() << '\n';
            continue;
        }
        write_file_atomically(destination, content, options.output_root);
        std::cout << "Wrote " << relative.generic_string() << '\n';
    }
    if (stale) {
        std::cout << "Generated files are stale.\n";
        return 1;
    }
    return 0;
}

void write_depfile(std::filesystem::path const& path,
                   Compilation const& compilation,
                   PublicationOptions const& options) {
    if (compilation.artifacts.empty()) {
        throw std::invalid_argument{"Cannot write a depfile for a compilation with no artifacts"};
    }

    auto escape_path = [](std::filesystem::path const& value) {
        auto const source{value.generic_string()};
        std::string escaped;
        escaped.reserve(source.size());
        for (char const character : source) {
            if (character == ' ' || character == '#') {
                escaped.push_back('\\');
            } else if (character == '$') {
                escaped.push_back('$');
            }
            escaped.push_back(character);
        }
        return escaped;
    };

    std::string content;
    for (std::size_t index{}; index < compilation.artifacts.size(); ++index) {
        if (index != 0) {
            content += ' ';
        }
        auto const& artifact_path{compilation.path(compilation.artifacts[index])};
        content += escape_path(options.output_root /
                               safe_relative_output_path(artifact_path, options.path_base));
    }
    content += ':';
    std::set<std::string> emitted_dependencies;
    for (auto const& dependency : compilation.dependencies) {
        auto const key{lispb::codegen::output_path_key(dependency)};
        if (!emitted_dependencies.insert(key).second) {
            continue;
        }
        content += ' ';
        content += escape_path(dependency);
    }
    content += '\n';

    auto const absolute{std::filesystem::absolute(path).lexically_normal()};
    write_file_atomically(absolute, content, absolute.parent_path());
}

