use clap::{Parser, Subcommand};
use std::{collections::BTreeSet, fs, path::PathBuf, process::Command};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

#[derive(Parser)]
struct Cli {
    #[command(subcommand)]
    command: Tool,
}

#[derive(Subcommand)]
enum Tool {
    MimallocSymbols {
        #[command(subcommand)]
        command: Operation,
    },
}

#[derive(Subcommand)]
enum Operation {
    Generate {
        #[command(flatten)]
        inputs: Inputs,
        #[arg(long)]
        output: PathBuf,
    },
    Verify {
        #[command(flatten)]
        inputs: Inputs,
    },
}

#[derive(clap::Args)]
struct Inputs {
    #[arg(long)]
    nm: PathBuf,
    #[arg(long)]
    readobj: PathBuf,
    #[arg(required = true)]
    objects: Vec<PathBuf>,
}

fn identifiers(text: &str) -> BTreeSet<&str> {
    text.split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
        .filter(|s| {
            s.trim_start_matches('_')
                .strip_prefix("mi_")
                .is_some_and(|tail| !tail.is_empty())
        })
        .collect()
}

fn includes(text: &str) -> BTreeSet<&str> {
    text.split_whitespace()
        .filter_map(|s| {
            s.get(..9)
                .filter(|prefix| prefix.eq_ignore_ascii_case("/include:"))
                .map(|_| &s[9..])
        })
        .filter(|s| !s.is_empty())
        .collect()
}

fn mimalloc_include(symbol: &str) -> bool {
    symbol.starts_with('_') && identifiers(symbol).contains(symbol)
}

fn without_string_literals(text: &str) -> String {
    // Ignore MSVC string-literal symbols when auditing allocator names.
    text.lines()
        .filter(|line| {
            !line
                .split_whitespace()
                .any(|part| part.starts_with("??_C@"))
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn render_header(symbols: &BTreeSet<&str>, directives: &BTreeSet<&str>) -> String {
    let mut header = String::from(
        "// Generated by native-binary-tools mimalloc-symbols. Do not edit.\n#pragma once\n\n",
    );

    for symbol in symbols {
        header.push_str(&format!("#define {symbol} sbx_{symbol}\n"));
    }

    let directives: Vec<_> = directives.iter().filter(|s| mimalloc_include(s)).collect();
    if !directives.is_empty() {
        header.push_str("\n#if defined(_MSC_VER)\n");
        for symbol in directives {
            header.push_str(&format!(
                "#pragma comment(linker, \"/include:sbx_{symbol}\")\n"
            ));
        }
        header.push_str("#endif\n");
    }
    header
}

fn inspect(executable: &PathBuf, args: &[&str], objects: &[PathBuf]) -> Result<String> {
    let mut output = String::new();

    for object in objects {
        let result = Command::new(executable)
            .args(args)
            .arg(object)
            .output()
            .map_err(|error| {
                format!(
                    "Unable to run '{}' for '{}': {error}",
                    executable.display(),
                    object.display()
                )
            })?;

        if !result.status.success() {
            return Err(format!(
                "'{}' failed for '{}' with {}.\n{}",
                executable.display(),
                object.display(),
                result.status,
                String::from_utf8_lossy(&result.stderr)
            )
            .into());
        }

        output.push_str(&String::from_utf8_lossy(&result.stdout));
        output.push('\n');
    }

    Ok(output)
}

fn reject(symbols: BTreeSet<&str>, description: &str) -> Result<()> {
    if symbols.is_empty() {
        return Ok(());
    }

    Err(format!(
        "{description}: {}",
        symbols.into_iter().collect::<Vec<_>>().join(", ")
    )
    .into())
}

fn verify_symbols(external: &str, undefined: &str, raw: &str, directives: &str) -> Result<()> {
    reject(
        identifiers(&without_string_literals(external)),
        "Unprefixed externally visible mimalloc identifiers remain",
    )?;

    reject(
        identifiers(&without_string_literals(undefined)),
        "Unprefixed mimalloc references remain",
    )?;

    reject(
        raw.lines()
            .filter(|s| {
                [
                    "_aligned_free",
                    "_aligned_malloc",
                    "_aligned_realloc",
                    "calloc",
                    "free",
                    "malloc",
                    "realloc",
                ]
                .contains(s)
                    || ["??2@", "??3@", "??_U@", "??_V@"]
                        .iter()
                        .any(|prefix| s.starts_with(prefix))
            })
            .collect(),
        "Allocator override symbols are defined",
    )?;

    reject(
        includes(directives)
            .into_iter()
            .filter(|s| mimalloc_include(s))
            .collect(),
        "Unprefixed mimalloc linker directives remain",
    )
}

fn run(command: Operation) -> Result<()> {
    match command {
        Operation::Generate { inputs, output } => {
            let symbols = inspect(
                &inputs.nm,
                &["--defined-only", "--extern-only", "--demangle"],
                &inputs.objects,
            )?;
            let symbols = identifiers(&symbols);
            if symbols.is_empty() {
                return Err("The mimalloc probe object exposed no allocator identifiers.".into());
            }

            let directives = inspect(&inputs.readobj, &["--coff-directives"], &inputs.objects)?;

            let output = std::path::absolute(output)?;
            fs::create_dir_all(output.parent().unwrap())?;
            fs::write(output, render_header(&symbols, &includes(&directives)))?;
            Ok(())
        }
        Operation::Verify { inputs } => verify_symbols(
            &inspect(
                &inputs.nm,
                &["--defined-only", "--extern-only"],
                &inputs.objects,
            )?,
            &inspect(
                &inputs.nm,
                &["--undefined-only", "--extern-only"],
                &inputs.objects,
            )?,
            &inspect(
                &inputs.nm,
                &["-j", "--defined-only", "--extern-only"],
                &inputs.objects,
            )?,
            &inspect(&inputs.readobj, &["--coff-directives"], &inputs.objects)?,
        ),
    }
}

fn main() {
    let Tool::MimallocSymbols { command } = Cli::parse().command;

    if let Err(error) = run(command) {
        eprintln!("native-binary-tools: {error}");
        std::process::exit(1);
    }
}

