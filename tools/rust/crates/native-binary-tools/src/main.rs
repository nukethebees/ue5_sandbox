use clap::{Parser, Subcommand};
use std::{collections::BTreeSet, fs, path::PathBuf, process::Command};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

#[derive(Parser)]
struct Cli {
    #[command(subcommand)]
    command: Tool,
}

#[derive(Subcommand)]
enum Tool {
    MimallocSymbols {
        #[command(subcommand)]
        command: Operation,
    },
}

#[derive(Subcommand)]
enum Operation {
    Generate {
        #[command(flatten)]
        inputs: Inputs,
        #[arg(long)]
        output: PathBuf,
    },
    Verify {
        #[command(flatten)]
        inputs: Inputs,
    },
}

#[derive(clap::Args)]
struct Inputs {
    #[arg(long)]
    nm: PathBuf,
    #[arg(long)]
    readobj: PathBuf,
    #[arg(required = true)]
    objects: Vec<PathBuf>,
}

fn identifiers(text: &str) -> BTreeSet<&str> {
    text.split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
        .filter(|s| {
            s.trim_start_matches('_')
                .strip_prefix("mi_")
                .is_some_and(|tail| !tail.is_empty())
        })
        .collect()
}

fn includes(text: &str) -> BTreeSet<&str> {
    text.split_whitespace()
        .filter_map(|s| {
            s.get(..9)
                .filter(|prefix| prefix.eq_ignore_ascii_case("/include:"))
                .map(|_| &s[9..])
        })
        .filter(|s| !s.is_empty())
        .collect()
}

fn mimalloc_include(symbol: &str) -> bool {
    symbol.starts_with('_') && identifiers(symbol).contains(symbol)
}

fn without_string_literals(text: &str) -> String {
    text.lines()
        .filter(|line| {
            !line
                .split_whitespace()
                .any(|part| part.starts_with("??_C@"))
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn render_header(symbols: &BTreeSet<&str>, directives: &BTreeSet<&str>) -> String {
    let mut header = String::from(
        "// Generated by native-binary-tools mimalloc-symbols. Do not edit.\n#pragma once\n\n",
    );
    for symbol in symbols {
        header.push_str(&format!("#define {symbol} sbx_{symbol}\n"));
    }
    let directives: Vec<_> = directives.iter().filter(|s| mimalloc_include(s)).collect();
    if !directives.is_empty() {
        header.push_str("\n#if defined(_MSC_VER)\n");
        for symbol in directives {
            header.push_str(&format!(
                "#pragma comment(linker, \"/include:sbx_{symbol}\")\n"
            ));
        }
        header.push_str("#endif\n");
    }
    header
}

fn inspect(executable: &PathBuf, args: &[&str], objects: &[PathBuf]) -> Result<String> {
    let mut output = String::new();
    for object in objects {
        let result = Command::new(executable)
            .args(args)
            .arg(object)
            .output()
            .map_err(|error| {
                format!(
                    "Unable to run '{}' for '{}': {error}",
                    executable.display(),
                    object.display()
                )
            })?;
        if !result.status.success() {
            return Err(format!(
                "'{}' failed for '{}' with {}.\n{}",
                executable.display(),
                object.display(),
                result.status,
                String::from_utf8_lossy(&result.stderr)
            )
            .into());
        }
        output.push_str(&String::from_utf8_lossy(&result.stdout));
        output.push('\n');
    }
    Ok(output)
}

fn reject(symbols: BTreeSet<&str>, description: &str) -> Result<()> {
    if symbols.is_empty() {
        return Ok(());
    }
    Err(format!(
        "{description}: {}",
        symbols.into_iter().collect::<Vec<_>>().join(", ")
    )
    .into())
}

fn verify_symbols(external: &str, undefined: &str, raw: &str, directives: &str) -> Result<()> {
    reject(
        identifiers(&without_string_literals(external)),
        "Unprefixed externally visible mimalloc identifiers remain",
    )?;
    reject(
        identifiers(&without_string_literals(undefined)),
        "Unprefixed mimalloc references remain",
    )?;
    reject(
        raw.lines()
            .filter(|s| {
                [
                    "_aligned_free",
                    "_aligned_malloc",
                    "_aligned_realloc",
                    "calloc",
                    "free",
                    "malloc",
                    "realloc",
                ]
                .contains(s)
                    || ["??2@", "??3@", "??_U@", "??_V@"]
                        .iter()
                        .any(|prefix| s.starts_with(prefix))
            })
            .collect(),
        "Allocator override symbols are defined",
    )?;
    reject(
        includes(directives)
            .into_iter()
            .filter(|s| mimalloc_include(s))
            .collect(),
        "Unprefixed mimalloc linker directives remain",
    )
}

fn run(command: Operation) -> Result<()> {
    match command {
        Operation::Generate { inputs, output } => {
            let symbols = inspect(
                &inputs.nm,
                &["--defined-only", "--extern-only", "--demangle"],
                &inputs.objects,
            )?;
            let symbols = identifiers(&symbols);
            if symbols.is_empty() {
                return Err("The mimalloc probe object exposed no allocator identifiers.".into());
            }
            let directives = inspect(&inputs.readobj, &["--coff-directives"], &inputs.objects)?;
            let output = std::path::absolute(output)?;
            fs::create_dir_all(output.parent().unwrap())?;
            fs::write(output, render_header(&symbols, &includes(&directives)))?;
            Ok(())
        }
        Operation::Verify { inputs } => verify_symbols(
            &inspect(
                &inputs.nm,
                &["--defined-only", "--extern-only"],
                &inputs.objects,
            )?,
            &inspect(
                &inputs.nm,
                &["--undefined-only", "--extern-only"],
                &inputs.objects,
            )?,
            &inspect(
                &inputs.nm,
                &["-j", "--defined-only", "--extern-only"],
                &inputs.objects,
            )?,
            &inspect(&inputs.readobj, &["--coff-directives"], &inputs.objects)?,
        ),
    }
}

fn main() {
    let Tool::MimallocSymbols { command } = Cli::parse().command;
    if let Err(error) = run(command) {
        eprintln!("native-binary-tools: {error}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_c_cpp_and_internal_symbols_without_prefixed_names() {
        assert_eq!(
            identifiers(
                "000 T mi_malloc\nT void _mi_heap_init(struct mi_heap_s *)\nT sbx_mi_free\nT ami_free\nT mi_"
            ),
            BTreeSet::from(["mi_malloc", "_mi_heap_init", "mi_heap_s"])
        );
    }

    #[test]
    fn header_is_sorted_and_only_rewrites_allocator_directives() {
        let header = render_header(
            &BTreeSet::from(["mi_malloc", "_mi_heap_init"]),
            &includes("/INCLUDE:_tls_used /include:_mi_tls_callback_pre"),
        );
        assert_eq!(
            header,
            "// Generated by native-binary-tools mimalloc-symbols. Do not edit.\n#pragma once\n\n#define _mi_heap_init sbx__mi_heap_init\n#define mi_malloc sbx_mi_malloc\n\n#if defined(_MSC_VER)\n#pragma comment(linker, \"/include:sbx__mi_tls_callback_pre\")\n#endif\n"
        );
    }

    #[test]
    fn audit_rejects_unprefixed_symbols_references_overrides_and_directives() {
        for (external, undefined, raw, directives, message) in [
            ("T mi_free", "", "", "", "externally visible"),
            ("", "U _mi_heap_init", "", "", "references"),
            ("", "", "malloc", "", "override"),
            ("", "", "??_V@YAXPEAX@Z", "", "override"),
            ("", "", "", "/INCLUDE:_mi_tls_callback_pre", "directives"),
        ] {
            assert!(
                verify_symbols(external, undefined, raw, directives)
                    .unwrap_err()
                    .to_string()
                    .contains(message)
            );
        }
        for symbol in [
            "??2@",
            "??3@",
            "??_U@",
            "??_V@",
            "_aligned_free",
            "calloc",
            "free",
            "realloc",
        ] {
            assert!(verify_symbols("", "", symbol, "").is_err());
        }
    }

    #[test]
    fn audit_accepts_prefixed_symbols_and_msvc_string_literals() {
        verify_symbols(
            "T sbx_mi_malloc\nR ??_C@_07LDBHFKDL@mi_free?$AA@",
            "U sbx__mi_heap_init",
            "sbx_mi_malloc",
            "/INCLUDE:_tls_used /include:sbx__mi_tls_callback_pre",
        )
        .unwrap();
    }

    #[test]
    fn arguments_require_tools_objects_and_generation_output() {
        let args = [
            "native-binary-tools",
            "mimalloc-symbols",
            "generate",
            "--nm",
            "llvm-nm",
            "--readobj",
            "llvm-readobj",
            "--output",
            "header.h",
            "object one.obj",
        ];
        assert!(Cli::try_parse_from(args).is_ok());
        assert!(Cli::try_parse_from(&args[..9]).is_err());
        assert!(Cli::try_parse_from(["tool", "mimalloc-symbols", "verify", "--nm", "nm"]).is_err());
        assert!(Cli::try_parse_from(args.into_iter().chain(["--nm", "other"])).is_err());
    }
}
